// Builds docs/RULES_COVERAGE.md: which Comprehensive Rules are tested.
// A rule counts as tested when a scenario lists it in "rules", or a test
// title (it/describe) mentions its number. Run with --check in CI to fail
// when the committed report is out of date.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const engine = join(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(engine, "..", "..", "docs", "RULES_COVERAGE.md");
const { rulesVersion, rules } = JSON.parse(
  readFileSync(join(engine, "rules", "index.json"), "utf8"),
);

const counts = new Map();
const add = (id) => counts.set(id, (counts.get(id) ?? 0) + 1);
const files = (dir, ext) =>
  readdirSync(dir, { recursive: true })
    .map(String)
    .filter((f) => f.endsWith(ext))
    .map((f) => join(dir, f));

for (const file of files(join(engine, "scenarios"), ".json")) {
  for (const id of JSON.parse(readFileSync(file, "utf8")).rules) add(id);
}
for (const file of files(join(engine, "test"), ".test.ts")) {
  const source = readFileSync(file, "utf8");
  for (const [, title] of source.matchAll(/(?:it|describe)\(\s*"([^"]*)"/g)) {
    for (const [id] of title.matchAll(/\b\d+(?:-\d+)+\b/g)) add(id);
  }
}

const known = new Set(rules.map((r) => r.id));
const unknown = [...counts.keys()].filter((id) => !known.has(id));
if (unknown.length > 0) {
  console.error(`Tests cite rule numbers that don't exist: ${unknown.join(", ")}`);
  process.exit(1);
}

const status = (r) => {
  if (counts.get(r.id)) return "Tested";
  if (r.scope === "heading") return "Section heading";
  if (r.scope === "effects") return "Phase 4 (effects)";
  if (r.scope === "cards") return "Phase 4 (card data)";
  if (r.scope === "no-gameplay") return "No gameplay effect";
  return "Not yet";
};
const engineRules = rules.filter((r) => r.scope === "engine");
const engineTested = engineRules.filter((r) => counts.get(r.id)).length;
const playable = rules.filter((r) => r.scope !== "heading" && r.scope !== "no-gameplay");
const allTested = playable.filter((r) => counts.get(r.id)).length;
const percent = (a, b) => `${Math.round((a / b) * 100)}%`;

const lines = [
  "# Rules coverage",
  "",
  "<!-- Generated by `pnpm coverage:rules`. Don't edit by hand. -->",
  "",
  `Comprehensive Rules version ${rulesVersion}.`,
  "",
  "| Group | Tested | Total | Coverage |",
  "| --- | --- | --- | --- |",
  `| Core rules (no card effects needed) | ${engineTested} | ${engineRules.length} | ${percent(engineTested, engineRules.length)} |`,
  `| All rules with gameplay effect | ${allTested} | ${playable.length} | ${percent(allTested, playable.length)} |`,
  "",
  "**Phase 4** rules need the card effect library or the card data format. Section headings and rules with no gameplay effect (copyright line, rarity, and so on) aren't counted.",
  "",
  "| Rule | Topic | Status | Tests |",
  "| --- | --- | --- | --- |",
  ...rules.map((r) => `| ${r.id} | ${r.topic} | ${status(r)} | ${counts.get(r.id) ?? 0} |`),
  "",
];
const report = lines.join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(output, "utf8");
  } catch {
    // Missing file counts as stale.
  }
  if (current !== report) {
    console.error(
      "docs/RULES_COVERAGE.md is out of date. Run `pnpm coverage:rules` and commit it.",
    );
    process.exit(1);
  }
  console.log(`Rules coverage is up to date (core ${engineTested}/${engineRules.length}).`);
} else {
  writeFileSync(output, report);
  console.log(
    `Wrote docs/RULES_COVERAGE.md (core ${engineTested}/${engineRules.length}, all ${allTested}/${playable.length}).`,
  );
}
